/**
 * Builds the help assistant's pre-built answer library: Claude reads each
 * guide once and drafts the questions people are likely to ask about every
 * section, with several phrasings and an answer each. The result is written
 * to src/modules/help-assistant/help-library.generated.ts, with a readable
 * copy in docs/help-library-review.md. READ IT before committing: those
 * answers are served as-is, with no AI call. To fix or drop an answer, edit
 * the generated .ts file (the review file is regenerated on the next run).
 *
 *   ANTHROPIC_API_KEY=... npm run help:library                  (all three guides)
 *   ANTHROPIC_API_KEY=... npm run help:library -- recruiter     (one guide)
 *   ... -- --model claude-sonnet-4-5                            (stronger model for this one-off job)
 *
 * Run `npm run help:sync` first if a guide changed. Libraries for guides you
 * don't rebuild are kept as they are. A library whose guide has changed since
 * is ignored at runtime (answered live) until it is rebuilt.
 */
import fs from 'fs';
import path from 'path';
import { LlmService } from '../src/llm/llm.service';
import { HELP_GUIDES } from '../src/modules/help-assistant/help-guides.generated';
import { HELP_LIBRARY } from '../src/modules/help-assistant/help-library.generated';
import { guideHash, HelpLibraries, HelpLibraryEntry, normalizeQuestion } from '../src/modules/help-assistant/help-library';
import type { HelpAudienceKey } from '../src/modules/help-assistant/help-assistant.dto';

const OUT = path.join(__dirname, '..', 'src', 'modules', 'help-assistant', 'help-library.generated.ts');
/** Human-readable copy for whoever reviews the answers (not read by the app). */
const REVIEW = path.join(__dirname, '..', '..', '..', 'docs', 'help-library-review.md');
const AUDIENCES: HelpAudienceKey[] = ['candidate', 'employer', 'recruiter'];

/** Top-level (##) sections with how many ### subsections each has. */
function topSections(markdown: string): { id: string; label: string; subsections: number }[] {
  const out: { id: string; label: string; subsections: number }[] = [];
  for (const line of markdown.split('\n')) {
    const m = /^(#{2,3})(?!#)\s+(.+?)\s*\{#([\w-]+)\}\s*$/.exec(line);
    if (!m) continue;
    if (m[1] === '##') out.push({ id: m[3], label: m[2], subsections: 0 });
    else if (out.length) out[out.length - 1].subsections += 1;
  }
  return out;
}

async function main() {
  if (!process.env.ANTHROPIC_API_KEY) {
    console.error('Set ANTHROPIC_API_KEY first.');
    process.exit(1);
  }
  const args = process.argv.slice(2);
  const modelIdx = args.indexOf('--model');
  const model = modelIdx >= 0 ? args[modelIdx + 1] : undefined;
  const picked = args.filter((a, i) => !a.startsWith('--') && args[i - 1] !== '--model') as HelpAudienceKey[];
  const targets = picked.length ? picked : AUDIENCES;
  for (const t of targets) {
    if (!AUDIENCES.includes(t)) throw new Error(`Unknown guide "${t}" — use candidate, employer or recruiter.`);
  }

  const llm = new LlmService();
  const libraries: HelpLibraries = { ...HELP_LIBRARY };

  for (const audience of targets) {
    const guide = HELP_GUIDES[audience];
    const sectionIds = guide.sections.map((s) => s.id);
    const entries: HelpLibraryEntry[] = [];
    const seen = new Set<string>();

    for (const section of topSections(guide.markdown)) {
      const count = Math.min(12, 5 + section.subsections * 2);
      process.stdout.write(`${audience} · ${section.label} (${count})… `);
      const drafts = await llm.draftHelpLibrarySection({
        audience,
        guide: guide.markdown,
        sectionIds,
        sectionId: section.id,
        sectionLabel: section.label,
        count,
        model,
      });
      let kept = 0;
      for (const d of drafts) {
        const key = normalizeQuestion(d.question);
        if (!key || seen.has(key) || !d.sectionIds.length) continue;
        seen.add(key);
        entries.push({ id: `${audience}-${section.id}-${++kept}`, ...d });
      }
      console.log(`${kept} kept`);
    }

    libraries[audience] = { guideHash: guideHash(guide.markdown), entries };
    console.log(`${audience}: ${entries.length} entries\n`);
  }

  const body =
    '// GENERATED by scripts/build-help-library.ts from the guides. Review the\n' +
    '// answers before committing; re-run `npm run help:library` after a guide edit\n' +
    '// (an audience whose guide changed is ignored until its library is rebuilt).\n' +
    "import type { HelpLibraries } from './help-library';\n\n" +
    `export const HELP_LIBRARY: HelpLibraries = ${JSON.stringify(libraries, null, 2)};\n`;
  fs.writeFileSync(OUT, body);

  const review: string[] = [
    '# Help assistant answer library — review copy',
    '',
    'Generated by `npm run help:library`. These answers are shown to users as-is, without an AI call.',
    'To change one, edit `apps/api/src/modules/help-assistant/help-library.generated.ts`.',
    '',
  ];
  for (const audience of AUDIENCES) {
    const lib = libraries[audience];
    if (!lib) continue;
    review.push(`## ${audience} (${lib.entries.length})`, '');
    for (const e of lib.entries) {
      review.push(`### ${e.question}`, '', `_Also matches:_ ${e.variants.join(' · ')}`, '', e.answer, '', `_Sections:_ ${e.sectionIds.join(', ')} · \`${e.id}\``, '');
    }
  }
  if (fs.existsSync(path.dirname(REVIEW))) fs.writeFileSync(REVIEW, review.join('\n'));
  console.log(`Written to ${path.relative(process.cwd(), OUT)} and docs/help-library-review.md — review the answers, then commit.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
